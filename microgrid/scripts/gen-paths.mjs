#!/usr/bin/env node
// Generate src/live/paths.ts and src/live/units.ts from sim/microgrid/tags.json (task-67).
// The page subscribes to one folder pattern (`[default]MG/**`); paths.ts only records what the model holds.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const TAGS = resolve(here, '../../sim/microgrid/tags.json');
const OUT = resolve(here, '../src/live');

const PREFIX = '[default]MG/';

const leaves = [];
(function walk(node, path) {
  const p = path ? `${path}/${node.name}` : node.name;
  if (node.tagType === 'Folder') node.tags.forEach((c) => walk(c, p));
  else leaves.push({ path: p.replace(/^MG\//, ''), unit: node.engUnit ?? '' });
})(JSON.parse(readFileSync(TAGS, 'utf8'))[0], '');

writeFileSync(
  `${OUT}/paths.ts`,
  `// GENERATED by scripts/gen-paths.mjs from sim/microgrid/tags.json. Do not edit.
// Names are relative to ${PREFIX}. ${leaves.length} leaf tags.

export const PREFIX = ${JSON.stringify(PREFIX)};
/** The single SSE subscription: every leaf tag under the folder (server-side expansion, initial snapshot). */
export const LIVE_PATTERN = PREFIX + '**';
/** Leaf tags in the model; the server confirms this number with \`event: subscribed\`. */
export const TAG_COUNT = ${leaves.length};
`,
);
const units = Object.fromEntries(leaves.filter((l) => l.unit).map((l) => [l.path, l.unit]));
writeFileSync(
  `${OUT}/units.ts`,
  `// GENERATED by scripts/gen-paths.mjs from sim/microgrid/tags.json. Do not edit.
export const UNITS: Readonly<Record<string, string>> = ${JSON.stringify(units, null, 1)};
`,
);
console.log(`gen-paths: ${leaves.length} leaf tags; subscription ${PREFIX}**`);
