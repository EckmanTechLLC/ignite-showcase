#!/usr/bin/env node
// Generate src/live/paths.ts and src/live/units.ts from the gateway tag model (sim/launch/tags.json).
// Run by predev/prebuild so the scene can never drift from the simulation's tag names.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const model = JSON.parse(readFileSync(resolve(here, '../../sim/launch/tags.json'), 'utf8'));
const outDir = resolve(here, '../src/live');
const PROVIDER = '[default]';

const leaves = [];
const walk = (node, prefix) => {
  const path = prefix ? `${prefix}/${node.name}` : node.name;
  if (node.tagType === 'Folder' || Array.isArray(node.tags)) {
    for (const child of node.tags ?? []) walk(child, path);
  } else {
    leaves.push({ name: path, unit: node.engUnit ?? '', type: node.dataType ?? '', trended: node.historyEnabled === true });
  }
};
for (const root of model) walk(root, '');

const header = '// GENERATED by scripts/gen-paths.mjs from sim/launch/tags.json. Do not edit.\n';
mkdirSync(outDir, { recursive: true });

const names = leaves.map((l) => `  '${l.name}',`).join('\n');
writeFileSync(
  join(outDir, 'paths.ts'),
  `${header}
/** Provider prefix of every gateway path. */
export const PROVIDER = '${PROVIDER}';

/** Tag names relative to the provider, e.g. 'Launch/Clock/Phase'. ${leaves.length} leaf tags. */
export const TAG_NAMES = [
${names}
] as const;

export type TagName = (typeof TAG_NAMES)[number];

/** Full gateway paths, e.g. '[default]Launch/Clock/Phase'. */
export const TAG_PATHS: string[] = TAG_NAMES.map((n) => PROVIDER + n);

export const TAG_COUNT = ${leaves.length};
`,
);

const units = leaves.map((l) => `  '${l.name}': '${l.unit}',`).join('\n');
const types = leaves.map((l) => `  '${l.name}': '${l.type}',`).join('\n');
writeFileSync(
  join(outDir, 'units.ts'),
  `${header}import type { TagName } from './paths';

/** Engineering unit of each tag as declared in the tag model ('' when unitless). */
export const UNITS: Record<TagName, string> = {
${units}
};

/** Ignition data type of each tag. */
export const DATA_TYPES: Record<TagName, string> = {
${types}
};
`,
);
const trended = leaves.filter((l) => l.trended && l.type !== 'Boolean' && l.type !== 'String');
writeFileSync(
  join(outDir, 'trended.ts'),
  `${header}import type { TagName } from './paths';

/** Numeric tags with history enabled in the tag model (${trended.length}): the telemetry channel picker. */
export const TRENDED: TagName[] = [
${trended.map((l) => `  '${l.name}',`).join('\n')}
];
`,
);
console.log(`gen-paths: ${leaves.length} tags -> src/live/paths.ts, units.ts, trended.ts`);
