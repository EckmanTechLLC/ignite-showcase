#!/usr/bin/env node
// Generate src/live/paths.ts and src/live/units.ts from sim/brewery/tags.json (task-73).
// The gateway caps one SSE subscription at 1000 expanded tags and the model holds more (the engine state under
// _Sim_/State is 131 tags the page never reads), so the single subscription is a list of folder patterns that
// covers every tag except EXCLUDE. paths.ts records what the model holds and what is subscribed.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const TAGS = resolve(here, '../../sim/brewery/tags.json');
const OUT = resolve(here, '../src/live');

const PREFIX = '[default]BR/';
/** Folders (relative to BR/) the page does not subscribe to. */
const EXCLUDE = ['_Sim_/State'];

const root = JSON.parse(readFileSync(TAGS, 'utf8'))[0];
const leaves = [];
(function walk(node, path) {
  const p = path ? `${path}/${node.name}` : node.name;
  if (node.tagType === 'Folder') node.tags.forEach((c) => walk(c, p));
  else leaves.push({ path: p.replace(/^BR\//, ''), unit: node.engUnit ?? '' });
})(root, '');

const excluded = (p) => EXCLUDE.some((e) => p === e || p.startsWith(e + '/'));
const counted = leaves.filter((l) => !excluded(l.path));

// Patterns: `folder/**` for every folder without an excluded descendant, `folder/*` (direct leaves) where one is excluded.
const patterns = [];
(function walk(node, path) {
  const rel = path.replace(/^BR\/?/, '');
  if (excluded(rel)) return;
  const hasExcluded = EXCLUDE.some((e) => e.startsWith(rel ? rel + '/' : ''));
  if (!hasExcluded && rel) return void patterns.push(`${PREFIX}${rel}/**`);
  if (node.tags.some((c) => c.tagType !== 'Folder')) patterns.push(`${PREFIX}${rel ? rel + '/' : ''}*`);
  for (const c of node.tags) if (c.tagType === 'Folder') walk(c, path ? `${path}/${c.name}` : c.name);
})(root, 'BR');

writeFileSync(
  `${OUT}/paths.ts`,
  `// GENERATED by scripts/gen-paths.mjs from sim/brewery/tags.json. Do not edit.
// Names are relative to ${PREFIX}. ${leaves.length} leaf tags in the model, ${counted.length} subscribed.

export const PREFIX = ${JSON.stringify(PREFIX)};
/** The single SSE subscription: folder patterns (server-side expansion, initial snapshot). */
export const LIVE_PATTERNS: string[] = ${JSON.stringify(patterns)};
/** Leaf tags in the model. */
export const MODEL_COUNT = ${leaves.length};
/** Leaf tags the patterns expand to; the server confirms this number with \`event: subscribed\`. */
export const TAG_COUNT = ${counted.length};
`,
);
const units = Object.fromEntries(counted.filter((l) => l.unit).map((l) => [l.path, l.unit]));
writeFileSync(
  `${OUT}/units.ts`,
  `// GENERATED by scripts/gen-paths.mjs from sim/brewery/tags.json. Do not edit.
export const UNITS: Readonly<Record<string, string>> = ${JSON.stringify(units, null, 1)};
`,
);
console.log(`gen-paths: ${leaves.length} leaf tags in the model, ${counted.length} subscribed in ${patterns.length} patterns`);
