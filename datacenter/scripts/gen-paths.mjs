#!/usr/bin/env node
// Generate src/live/paths.ts and src/live/units.ts from sim/datacenter/tags.json (task-56, task-64).
// The page subscribes to one folder pattern (`[default]DC/**`); paths.ts only records what the scene renders.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const TAGS = resolve(here, '../../sim/datacenter/tags.json');
const OUT = resolve(here, '../src/live');

const PREFIX = '[default]DC/';

/** What the scene renders (task-56 deliverable 1). Names are relative to DC/. */
const SELECT = [
  /^Hall\/[^/]+$/,
  /^Power\/Utility\/[^/]+$/,
  /^Power\/Generator\/[^/]+$/,
  /^Power\/Switchgear\/[^/]+$/,
  /^Power\/UPS\/[^/]+\/[^/]+$/,
  /^Power\/PDU\/[^/]+\/(LoadKW|LoadPct|BreakerTripped|Feed)$/,
  /^Racks\/R(0[1-9]|[1-5]\d|60)\/(PowerKW|InletTempC|OutletTempC|UtilPct|Online|Workload|Row|FeedA|FeedB)$/,
  /^Cooling\/.+$/,
  /^_Sim_\/(Scenario|SpeedFactor|WorkloadProfile)$/,
];
const leaves = [];
(function walk(node, path) {
  const p = path ? `${path}/${node.name}` : node.name;
  if (node.tagType === 'Folder') node.tags.forEach((c) => walk(c, p));
  else leaves.push({ path: p.replace(/^DC\//, ''), unit: node.engUnit ?? '' });
})(JSON.parse(readFileSync(TAGS, 'utf8'))[0], '');

const selected = leaves.filter((l) => SELECT.some((r) => r.test(l.path)));
writeFileSync(
  `${OUT}/paths.ts`,
  `// GENERATED by scripts/gen-paths.mjs from sim/datacenter/tags.json. Do not edit.
// Names are relative to ${PREFIX}. ${selected.length} of ${leaves.length} tags are rendered by the scene.

export const PREFIX = ${JSON.stringify(PREFIX)};
/** The single SSE subscription: every leaf tag under the folder (server-side expansion, initial snapshot). */
export const LIVE_PATTERN = PREFIX + '**';
/** Tags the scene reads (all arrive over the one stream). */
export const SELECTED_COUNT = ${selected.length};
`,
);
const units = Object.fromEntries(selected.filter((l) => l.unit).map((l) => [l.path, l.unit]));
writeFileSync(
  `${OUT}/units.ts`,
  `// GENERATED by scripts/gen-paths.mjs from sim/datacenter/tags.json. Do not edit.
export const UNITS: Readonly<Record<string, string>> = ${JSON.stringify(units, null, 1)};
`,
);
console.log(`gen-paths: ${selected.length} of ${leaves.length} tags rendered; subscription ${PREFIX}**`);
