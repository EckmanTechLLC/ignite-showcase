#!/usr/bin/env node
// Generate src/live/paths.ts and src/live/units.ts from sim/datacenter/tags.json (task-56).
// Also asserts the SSE limits: <= 100 paths per connection, <= 4 connections, URL < 6 000 chars.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const TAGS = resolve(here, '../../sim/datacenter/tags.json');
const OUT = resolve(here, '../src/live');

const MAX_PER_CHUNK = 100;
const MAX_CHUNKS = 4;
const MAX_URL = 6000;
const MAX_LIVE = 400;
const PREFIX = '[default]DC/';

/** What the scene renders (task-56 deliverable 1). Names are relative to DC/. */
const SELECT = [
  /^Hall\/[^/]+$/,
  /^Power\/Utility\/[^/]+$/,
  /^Power\/Generator\/[^/]+$/,
  /^Power\/Switchgear\/[^/]+$/,
  /^Power\/UPS\/[^/]+\/[^/]+$/,
  /^Power\/PDU\/[^/]+\/(LoadKW|LoadPct|BreakerTripped|Feed)$/,
  /^Racks\/R(0[1-9]|[1-5]\d|60)\/(PowerKW|InletTempC|OutletTempC|UtilPct|Online|Workload|Row|FeedA|FeedB)$/,
  /^Cooling\/.+$/,
  /^_Sim_\/(Scenario|SpeedFactor|WorkloadProfile)$/,
];
/**
 * Constants (never written by the sim). They are read with /tags/read at start and refreshed slowly,
 * not subscribed: 60 racks x 9 tags alone is 540 paths, more than four SSE connections can carry.
 */
const STATIC = [
  /^Hall\/CapacityKW$/,
  /^Racks\/R\d+\/(Workload|Row|FeedA|FeedB)$/,
  /^Power\/PDU\/[^/]+\/Feed$/,
  /^Cooling\/CRAH\/\d+\/Zone$/,
];

const leaves = [];
(function walk(node, path) {
  const p = path ? `${path}/${node.name}` : node.name;
  if (node.tagType === 'Folder') node.tags.forEach((c) => walk(c, p));
  else leaves.push({ path: p.replace(/^DC\//, ''), unit: node.engUnit ?? '' });
})(JSON.parse(readFileSync(TAGS, 'utf8'))[0], '');

const selected = leaves.filter((l) => SELECT.some((r) => r.test(l.path)));
const isStatic = (l) => STATIC.some((r) => r.test(l.path));
const live = selected.filter((l) => !isStatic(l)).map((l) => l.path);
const fixed = selected.filter(isStatic).map((l) => l.path);

function chunk(paths) {
  const n = Math.ceil(paths.length / MAX_PER_CHUNK);
  const size = Math.ceil(paths.length / n);
  return Array.from({ length: n }, (_, i) => paths.slice(i * size, (i + 1) * size));
}
const liveChunks = chunk(live);
const staticChunks = chunk(fixed);

// Worst-case URL: gateway origin + /data/ignite/sse + paths + site + a generous 128-char key.
const url = (c) =>
  `${'o'.repeat(24)}/data/ignite/sse?` +
  new URLSearchParams({ paths: c.map((p) => PREFIX + p).join(','), site: 'datacenter', apiKey: 'k'.repeat(128) });
const longest = Math.max(...liveChunks.map((c) => url(c).length), ...staticChunks.map((c) => url(c).length));

const fail = (m) => {
  console.error(`gen-paths: ${m}`);
  process.exit(1);
};
if (live.length > MAX_LIVE) fail(`${live.length} live paths > ${MAX_LIVE}`);
if (liveChunks.length > MAX_CHUNKS) fail(`${liveChunks.length} SSE connections > ${MAX_CHUNKS}`);
if (liveChunks.some((c) => c.length > MAX_PER_CHUNK)) fail('chunk over 100 paths');
if (longest >= MAX_URL) fail(`longest URL ${longest} >= ${MAX_URL}`);

const q = (a) => JSON.stringify(a);
const rows = (chunks) => chunks.map((c) => `  [\n${c.map((p) => `    ${q(p)},`).join('\n')}\n  ],`).join('\n');
writeFileSync(
  `${OUT}/paths.ts`,
  `// GENERATED by scripts/gen-paths.mjs from sim/datacenter/tags.json. Do not edit.
// Names are relative to ${PREFIX}. ${selected.length} tags selected: ${live.length} live (SSE), ${fixed.length} constants (polled).

export const PREFIX = ${q(PREFIX)};
export const LIVE_COUNT = ${live.length};
export const STATIC_COUNT = ${fixed.length};
export const SELECTED_COUNT = ${selected.length};
/** Longest SSE / read URL (chars) with a 128-char key, asserted < ${MAX_URL} at generation time. */
export const LONGEST_URL = ${longest};

/** Subscribed over SSE, one connection per chunk (<= ${MAX_PER_CHUNK} paths, <= ${MAX_CHUNKS} chunks). */
export const LIVE_CHUNKS: readonly (readonly string[])[] = [
${rows(liveChunks)}
];

/** Constants, read with /tags/read and refreshed slowly. */
export const STATIC_CHUNKS: readonly (readonly string[])[] = [
${rows(staticChunks)}
];
`,
);
const units = Object.fromEntries(selected.filter((l) => l.unit).map((l) => [l.path, l.unit]));
writeFileSync(
  `${OUT}/units.ts`,
  `// GENERATED by scripts/gen-paths.mjs from sim/datacenter/tags.json. Do not edit.
export const UNITS: Readonly<Record<string, string>> = ${JSON.stringify(units, null, 1)};
`,
);
console.log(
  `gen-paths: ${selected.length} selected = ${live.length} live in ${liveChunks.length} SSE chunks (${liveChunks
    .map((c) => c.length)
    .join('/')}) + ${fixed.length} constants in ${staticChunks.length} read chunks; longest URL ${longest} chars`,
);
